# Q39. Create a nested list and access inner elements.

nested = [[10, 20, 30], [40, 50, 60], [70, 80, 90]]
print("Nested list:", nested)
print("First inner list:", nested[0])
print("Element at [0][1]:", nested[0][1])
print("Element at [1][2]:", nested[1][2])
print("Element at [2][0]:", nested[2][0])
